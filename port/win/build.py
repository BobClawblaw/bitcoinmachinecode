def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        raise RuntimeError('command failed: %s\n%s%s' % (' '.join(cmd), r.stdout, r.stderr))
    return r


def newer(target, *sources):
    if not os.path.exists(target):
        return True
    t = os.path.getmtime(target)
    return any(os.path.getmtime(s) > t for s in sources if os.path.exists(s))


def _dep_list(dfile):
    """Parse a make-style depfile into a list of prerequisite paths."""
    try:
        with open(dfile) as f:
            text = f.read().replace('\\\n', ' ')
    except OSError:
        return None
    body = text.split(':', 1)[1] if ':' in text[2:] else text
    # a Windows path has its own colon (C:/...) -- split on the rule colon
    m = re.match(r'^(.*?\.(?:ll|o|obj)):\s', text)
    if m:
        body = text[m.end():]
    return [p.replace('\\ ', ' ') for p in re.split(r'(?<!\\)\s+', body.strip()) if p]


def stale(obj, src, dfile):
    if newer(obj, src):
        return True
    deps = _dep_list(dfile)
    if deps is None:
        return True
    return newer(obj, *deps)


# ---------------------------------------------------------------- musl
def fetch_musl():
    if os.path.exists(os.path.join(MUSL, 'VERSION')):
        return
    os.makedirs(DEPS, exist_ok=True)
    tgz = os.path.join(DEPS, 'musl-%s.tar.gz' % MUSL_VER)
    if not os.path.exists(tgz):
        print('fetch', MUSL_URL)
        urllib.request.urlretrieve(MUSL_URL, tgz)
    h = hashlib.sha256(open(tgz, 'rb').read()).hexdigest()
    if h != MUSL_SHA256:
        os.remove(tgz)
        sys.exit('build.py: musl tarball sha256 mismatch: %s' % h)
    with tarfile.open(tgz) as t:
        t.extractall(DEPS, filter='data')


def musl_headers():
    """Generate musl's obj/include/bits/{alltypes,syscall}.h and version.h."""
    inc = os.path.join(MUSL_OBJ, 'include', 'bits')
    os.makedirs(inc, exist_ok=True)
    out = os.path.join(inc, 'alltypes.h')
    if not os.path.exists(out):
        text = ''
        for src in (os.path.join(MUSL, 'arch', 'x86_64', 'bits', 'alltypes.h.in'),
                    os.path.join(MUSL, 'include', 'alltypes.h.in')):
            text += open(src).read()
        res = []
        for ln in text.split('\n'):
            m = re.match(r'^TYPEDEF (.*) ([^ ]*);$', ln)
            if m:
                ln = ('#if defined(__NEED_{1}) && !defined(__DEFINED_{1})\ntypedef {0} {1};\n'
                      '#define __DEFINED_{1}\n#endif\n').format(m.group(1), m.group(2))
            m = re.match(r'^(STRUCT|UNION) * ([^ ]*) (.*);$', ln)
            if m:
                kw = m.group(1).lower()
                ln = ('#if defined(__NEED_{0}_{1}) && !defined(__DEFINED_{0}_{1})\n{0} {1} {2};\n'
                      '#define __DEFINED_{0}_{1}\n#endif\n').format(kw, m.group(2), m.group(3))
            res.append(ln)
        open(out, 'w', newline='\n').write('\n'.join(res))
    out = os.path.join(inc, 'syscall.h')
    if not os.path.exists(out):
        text = open(os.path.join(MUSL, 'arch', 'x86_64', 'bits', 'syscall.h.in')).read()
        extra = '\n'.join(re.sub(r'__NR_', 'SYS_', ln) for ln in text.split('\n') if '__NR_' in ln)
        open(out, 'w', newline='\n').write(text + '\n' + extra + '\n')
    vdir = os.path.join(MUSL_OBJ, 'src', 'internal')
    os.makedirs(vdir, exist_ok=True)
    v = os.path.join(vdir, 'version.h')
    if not os.path.exists(v):
        open(v, 'w', newline='\n').write('#define VERSION "%s-bmc_win"\n' % MUSL_VER)


# musl files that bmc_win replaces (port/win/rt) or that cannot exist on
# Windows (dynamic linker, clone-based threads, x86 asm with ELF directives).
MUSL_EXCLUDE = {
    'src/env/__init_tls.c', 'src/env/__reset_tls.c',
    'src/thread/pthread_create.c', 'src/thread/pthread_join.c', 'src/thread/pthread_detach.c',
    'src/thread/pthread_cancel.c', 'src/thread/pthread_testcancel.c',
    'src/thread/synccall.c', 'src/thread/__unmapself.c', 'src/linux/clone.c',
    'src/thread/pthread_getattr_np.c', 'src/thread/__set_thread_area.c',
    'src/internal/vdso.c',
    'src/network/getaddrinfo.c', 'src/network/freeaddrinfo.c',
}
MUSL_EXCLUDE_DIRS = {'src/malloc', 'src/ldso', 'src/aio', 'src/mq', 'src/ipc', 'src/crypt'}


def musl_sources():
    base, arch = [], {}
    for d in sorted(glob.glob(os.path.join(MUSL, 'src', '*'))):
        rel = os.path.relpath(d, MUSL).replace('\\', '/')
        if rel in MUSL_EXCLUDE_DIRS:
            continue
        for f in sorted(glob.glob(os.path.join(d, '*.c'))):
            base.append(f)
        for f in sorted(glob.glob(os.path.join(d, 'x86_64', '*.c'))):
            arch[os.path.splitext(os.path.basename(f))[0]] = f
    out = []
    for f in base:
        rel = os.path.relpath(f, MUSL).replace('\\', '/')
        if rel in MUSL_EXCLUDE:
            continue
        stem = os.path.splitext(os.path.basename(f))[0]
        out.append(arch.pop(stem, f) if os.path.basename(os.path.dirname(f)) != 'x86_64' else f)
    out.extend(arch.values())
    return out


