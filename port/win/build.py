# ---------------------------------------------------------------- compilers
SYSV_COMMON = ['--target=x86_64-pc-linux-gnu', '-fno-pic', '-fno-pie', '-fno-plt',
               '-mstack-protector-guard=global', '-fno-asynchronous-unwind-tables',
               '-ffunction-sections', '-fdata-sections']


RETARGET_PY = os.path.join(HERE, 'tools', 'retarget.py')


def cc_sysv(src, obj, flags, opt='-O2'):
    """C (SysV/LP64 semantics) -> COFF object, via retargeted IR."""
    dfile = obj + '.d'
    if not stale(obj, src, dfile) and not newer(obj, RETARGET_PY):
        return obj
    os.makedirs(os.path.dirname(obj), exist_ok=True)
    ll = obj + '.ll'
    run([CLANG] + SYSV_COMMON + [opt] + flags +
        ['-MD', '-MF', dfile, '-MT', ll, '-emit-llvm', '-S', src, '-o', ll])
    with open(ll, encoding='utf-8') as f:
        text = retarget.retarget_text(f.read())
    wll = obj + '.w.ll'
    with open(wll, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    run([CLANG, '--target=x86_64-pc-windows-msvc', opt, '-Wno-override-module',
         '-ffunction-sections', '-fdata-sections', '-c', wll, '-o', obj])
    os.remove(ll)
    os.remove(wll)
    return obj


def _win_includes():
    """Windows SDK + MSVC headers for winsys (env BMC_WIN_INCLUDE: ';'-separated)."""
    if os.environ.get('BMC_WIN_INCLUDE'):
        dirs = os.environ['BMC_WIN_INCLUDE'].split(';')
    else:
        sdk = os.path.dirname(os.path.dirname(_winsdk_lib()))   # ...\Lib\<ver>
        ver = os.path.basename(sdk)
        inc = os.path.join(os.path.dirname(os.path.dirname(sdk)), 'Include', ver)
        dirs = [os.path.join(inc, d) for d in ('ucrt', 'um', 'shared')]
        vc = sorted(glob.glob(r'C:\Program Files*\Microsoft Visual Studio\*\*\VC\Tools\MSVC\*\include'))
        if not vc:
            sys.exit('build.py: MSVC headers not found (set BMC_WIN_INCLUDE)')
        dirs.append(vc[-1])
    out = []
    for d in dirs:
        out += ['-isystem', d]
    return out


WINSYS_CFLAGS = ['--target=x86_64-pc-windows-msvc', '-O2', '-ffreestanding', '-fno-builtin',
                 '-fno-stack-protector', '-fno-asynchronous-unwind-tables', '-mno-stack-arg-probe',
                 '-Wall', '-Werror', '-Wno-unused-function',
                 '-D_WIN32_WINNT=0x0A00', '-DWIN32_LEAN_AND_MEAN', '-DUNICODE', '-D_UNICODE']


def cc_win(src, obj, flags=()):
    dfile = obj + '.d'
    if not stale(obj, src, dfile):
        return obj
    os.makedirs(os.path.dirname(obj), exist_ok=True)
    run([CLANG] + WINSYS_CFLAGS + _win_includes() + list(flags) + ['-MD', '-MF', dfile, '-MT', obj, '-c', src, '-o', obj])
    return obj


def nasm_win(src, obj, extra_inc=(), defines=()):
    """Assemble one bmc .asm for win64 through the asm transform."""
    xs = obj + '.asm'
    os.makedirs(os.path.dirname(obj), exist_ok=True)
    incs = [os.path.dirname(os.path.abspath(src))] + list(extra_inc)
    deps = [src, os.path.join(HERE, 'tools', 'asm_xform.py'), os.path.join(HERE, 'asm', 'win_prelude.inc')]
    if not newer(obj, *deps) and not stale(obj, src, obj + '.d'):
        return obj
    with open(src, encoding='utf-8') as f:
        text = asm_xform.transform(f.read(), os.path.basename(src))
    with open(xs, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    cmd = [NASM, '-f', 'win64', '-Werror', '-w-zeroing', '-w-ea-absolute',
           '-I' + os.path.join(HERE, 'asm') + os.sep]
    for i in incs:
        cmd.append('-I' + i + os.sep)
    run(cmd + list(defines) + ['-MD', obj + '.d', '-MT', obj, '-o', obj, xs])
    return obj


def nasm_plain(src, obj):
    if not newer(obj, src):
        return obj
    os.makedirs(os.path.dirname(obj), exist_ok=True)
    run([NASM, '-f', 'win64', '-Werror', '-o', obj, src])
    return obj


def parallel(fn, items):
    errs = []
    res = []
    with cf.ThreadPoolExecutor(JOBS) as ex:
        futs = {ex.submit(fn, *it): it for it in items}
        for fu in cf.as_completed(futs):
            try:
                res.append(fu.result())
            except Exception as e:  # noqa: BLE001
                errs.append(str(e))
    return res, errs


def archive(lib, objs):
    rsp = lib + '.rsp'
    listing = '\n'.join('"%s"' % o for o in objs)
    same = os.path.exists(rsp) and open(rsp).read() == listing
    if same and os.path.exists(lib) and not newer(lib, *objs):
        return lib
    if os.path.exists(lib):
        os.remove(lib)
    with open(rsp, 'w') as f:
        f.write(listing)
    run([LLVM_LIB, '/out:' + lib, '@' + rsp])
    return lib


# ---------------------------------------------------------------- libraries
@functools.lru_cache(maxsize=None)
def build_musl():
    fetch_musl()
    musl_headers()
    flags = musl_cflags()
    items = []
    for src in musl_sources():
        rel = os.path.relpath(src, MUSL)
        obj = os.path.join(MUSL_OBJ, os.path.splitext(rel)[0] + '.obj')
        items.append((src, obj, flags, '-Os'))
    objs, errs = parallel(cc_sysv, items)
    if errs:
        for e in errs[:20]:
            print(e[:1500])
        sys.exit('musl: %d of %d files failed' % (len(errs), len(items)))
    return archive(os.path.join(OUT, 'libmusl.lib'), sorted(objs))


RT_SRCS = sorted(glob.glob(os.path.join(HERE, 'rt', '*.c')))
WINSYS_SRCS = sorted(glob.glob(os.path.join(HERE, 'winsys', '*.c')))
WINSYS_ASM = sorted(glob.glob(os.path.join(HERE, 'winsys', '*.asm')))


@functools.lru_cache(maxsize=None)
def build_rt():
    """rt: the SysV-side runtime (startup, pthreads, malloc) -- musl internals visible."""
    flags = musl_cflags() + ['-Wall', '-Werror']
    items = [(s, os.path.join(OUT, 'rt', os.path.basename(s)[:-2] + '.obj'), flags, '-O2') for s in RT_SRCS]
    objs, errs = parallel(cc_sysv, items)
    if errs:
        sys.exit('\n'.join(errs))
    return sorted(objs)


@functools.lru_cache(maxsize=None)
def build_winsys():
    items = [(s, os.path.join(OUT, 'winsys', os.path.basename(s)[:-2] + '.obj'),
              ['-I' + os.path.join(HERE, 'winsys')]) for s in WINSYS_SRCS]
    objs, errs = parallel(cc_win, items)
    if errs:
        sys.exit('\n'.join(errs))
    for s in WINSYS_ASM:
        objs.append(nasm_plain(s, os.path.join(OUT, 'winsys', os.path.basename(s)[:-4] + '.obj')))
    return sorted(objs)


