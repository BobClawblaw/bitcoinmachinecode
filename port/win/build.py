def user_inc():
    """The include path user code (bmc, rt) sees: musl's public headers."""
    return ['-nostdinc', '-isystem', os.path.join(HERE, 'include'),
            '-isystem', os.path.join(MUSL_OBJ, 'include'),
            '-isystem', os.path.join(MUSL, 'arch', 'x86_64'),
            '-isystem', os.path.join(MUSL, 'arch', 'generic'),
            '-isystem', os.path.join(MUSL, 'include'),
            '-isystem', _clang_resource_inc()]


_RES = None


def _clang_resource_inc():
    global _RES
    if _RES is None:
        r = run([CLANG, '-print-resource-dir'])
        _RES = os.path.join(r.stdout.strip(), 'include')
