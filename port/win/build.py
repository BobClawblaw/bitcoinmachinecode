#!/usr/bin/env python3
"""build.py -- native Windows (x86-64) build driver for bmc (bmc_win).

Layout of the result (see port/WIN_STRATEGY.md):
  * the bmc C code and a static musl are compiled for x86_64-linux (LP64,
    SysV) to LLVM IR, retargeted to Windows COFF (tools/retarget.py) and
    code-generated by clang -- C semantics identical to the Linux build;
  * the NASM sources are assembled -f win64 after tools/asm_xform.py turns
    `syscall` into a call to the emulation and the ELF TLS macro into PE TLS;
  * port/win/winsys (the only Win64-ABI code) emulates the Linux syscalls on
    Win32 and provides the process entry, TLS directory and stack probe.
No MSVC CRT is linked.

Usage:  python port/win/build.py [targets...]   (default: the phase list)
        python port/win/build.py --list
Env:    BMC_LLVM (dir with clang.exe/lld-link.exe), BMC_NASM (nasm.exe),
        BMC_WINSDK_LIB (dir holding kernel32.lib etc.), BMC_JOBS.
"""
