# ---------------------------------------------------------------- tools
def _find_tool(env, names, dirs):
    if os.environ.get(env):
        return os.environ[env]
    for n in names:
        p = shutil.which(n)
        if p:
            return p
        for d in dirs:
            c = os.path.join(d, n)
            if os.path.exists(c):
                return c
    sys.exit('build.py: cannot find %s (set %s)' % (names[0], env))


