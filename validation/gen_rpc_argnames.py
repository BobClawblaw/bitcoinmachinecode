#!/usr/bin/env python3
"""validation/gen_rpc_argnames.py -- every RPC method's argument names, in
Bitcoin Core's order, for named-argument requests (2026-11-06).

Core converts a JSON-RPC `params` OBJECT to positions with each method's
argument names (rpc/server.cpp transformNamedArguments, the names from
RPCHelpMan::GetArgNames). This node had no such table, so a named request
reached every handler except echo's unconverted. This script reads the
names from a running Core's `help`, which prints each argument's first name
in order and, for an options object that takes named arguments
(OBJ_NAMED_PARAMS), its inner names under "Named Arguments:"; GetArgNames
puts those inner names just before the options slot itself. `help` drops two
things the script adds from Core's source (checked against v31.1):

  * aliases: getblock and getrawtransaction name their second argument
    "verbosity|verbose";
  * hidden arguments: stop takes a hidden "wait";
  * hidden methods: `help` does not list the "hidden" category (echo,
    invalidateblock, the generate* calls, ...), though `help <method>`
    documents each; the list is v31.1's ({"hidden", &...} in src/rpc and
    src/wallet/rpc).

Writes asm/rpc_argnames.h: one entry per method, sorted, the names joined by
commas, a leading '*' marking a named-only (options) name.

    python3 validation/gen_rpc_argnames.py <bitcoin-cli> [cli args ...]
e.g. python3 validation/gen_rpc_argnames.py /path/bitcoin-cli -datadir=/tmp/regtest
"""
import os, re, subprocess, sys

ALIASES = {("getblock", "verbosity"): "verbosity|verbose",
           ("getrawtransaction", "verbosity"): "verbosity|verbose"}
HIDDEN = {"stop": ["wait"]}
HIDDEN_METHODS = ["addconnection", "addpeeraddress", "echo", "echoipc", "echojson", "estimaterawfee",
                  "generate", "generateblock", "generatetoaddress", "generatetodescriptor",
                  "getmempoolfeeratediagram", "getorphantxs", "getrawaddrman", "invalidateblock",
                  "mockscheduler", "reconsiderblock", "sendmsgtopeer", "setmocktime",
                  "syncwithvalidationinterfacequeue"]
NAMED_PARAMS_TEXT = "Options object that can be used to pass named arguments"

def cli(base, *args):
    return subprocess.run(base + list(args), capture_output=True, text=True, check=True).stdout

def names_of(base, method):
    text = cli(base, "help", method)
    pos, inner, section = [], [], None
    for line in text.splitlines():
        if line.startswith("Arguments:"): section = "args"; continue
        if line.startswith("Named Arguments:"): section = "named"; continue
        if line.startswith("Result") or line.startswith("Examples:"): section = None; continue
        if section == "args":
            m = re.match(r"^(\d+)\. (\S+)\s+\((.*)$", line)
            if m:
                if int(m.group(1)) != len(pos) + 1: sys.exit(f"{method}: argument {m.group(1)} out of order")
                pos.append((m.group(2), NAMED_PARAMS_TEXT in line))
        elif section == "named":
            m = re.match(r"^([a-z_][a-z0-9_]*)\s+\(", line)   # top level only: nested fields are indented
            if m: inner.append(m.group(1))
    out = []
    for name, takes_named in pos:
        if takes_named: out += ["*" + n for n in inner]
        out.append(ALIASES.get((method, name), name))
    out += HIDDEN.get(method, [])
    return out

def main():
    if len(sys.argv) < 2: sys.exit(__doc__)
    base = sys.argv[1:]
    version = cli(base, "getnetworkinfo").split('"subversion": "')[1].split('"')[0]
    methods = sorted({l.split()[0] for l in cli(base, "help").splitlines() if l and not l.startswith("==")} | set(HIDDEN_METHODS))
    rows = [(m, names_of(base, m)) for m in methods]
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "asm", "rpc_argnames.h")
    with open(out, "w") as f:
        f.write("/* asm/rpc_argnames.h -- GENERATED by validation/gen_rpc_argnames.py from\n"
                f" * Bitcoin Core {version}'s help; do not edit by hand. Each method's argument\n"
                " * names in Core's order (RPCHelpMan::GetArgNames): comma-separated, '|'\n"
                " * between aliases, a leading '*' on a named-only name (an options object's\n"
                " * field). Sorted by method for bsearch. Read by rpc_named_params\n"
                " * (rpc_commands.c). */\n"
                "#ifndef RPC_ARGNAMES_H\n#define RPC_ARGNAMES_H\n"
                "typedef struct { const char* method; const char* names; } rpc_argnames_t;\n"
                "static const rpc_argnames_t RPC_ARGNAMES[] = {\n")
        for m, ns in rows:
            f.write(f'    {{"{m}", "{",".join(ns)}"}},\n')
        f.write("};\n#endif\n")
    print(f"{len(rows)} methods from {version} -> {os.path.normpath(out)}")

if __name__ == "__main__":
    main()
