/* test_tapscript_scale.c -- inscription-SCALE tapscript coverage.
 *
 * CHAIN_AHEAD_CENSUS.md's Outcome table (2026-08-22) left two rows open:
 *
 *   | ">10 KB tapscript / real inscription" untested at scale | **Still open.**
 *     ... The single biggest remaining untested risk, unchanged. |
 *   | `tap_leaf_hash` 4 MB leaf cap | Still open, design-worthy-not-urgent. |
 *
 * This closes both with REAL mainnet transactions -- the largest tapscript
 * leaf, the deepest control block and the widest script-path witness stack
 * the chain has ever carried -- each driven through the real block-connection
 * dispatch tx_verify_block_connect, exactly like tests/test_segwit_coverage.c.
 *
 * WHAT MAKES THE NEGATIVE CASES LOAD-BEARING: a verifier that silently
 * TRUNCATED a large leaf (a fixed buffer, a u16 length, a capped memcpy) would
 * still ACCEPT the unmodified fixture, because the truncated prefix hashes
 * consistently on both sides of nothing. So for every fixture we also flip the
 * LAST byte of the leaf script and require a "commitment mismatch" rejection --
 * that byte only changes the answer if the WHOLE leaf actually reached
 * tap_leaf_hash. Same idea for the deepest control block (flip its last merkle
 * node) and for the widest witness (flip a byte of the first initial-stack
 * item, which only matters if all 10 items were really pushed).
 *
 * IT ALSO CARRIES THE INCIDENT #18 REGRESSION. Looking for a size wall on
 * this path turned up a different bug beside it: the tapscript initial stack
 * had no MAX_SCRIPT_ELEMENT_SIZE check at all, so a >524-byte initial-stack
 * item overran a 528,000-byte heap buffer, and a 521-byte one was a silent
 * consensus false-accept. That shape does not exist on mainnet (47,578 sampled
 * real script-path inputs top out at a 79-byte initial-stack item), so those
 * four vectors are synthetic -- with their verdicts taken from Bitcoin Core
 * itself via validation/diff_tapscript_stack.py, not from this author. See
 * tapscript_stack_vec.h.
 *
 * Fixtures are generated by validation/fetch_tapscript_scale.py:
 *   - <=64 KB raw tx  -> inlined in tapscript_scale_vec.h (always runs, no oracle)
 *   - >64 KB raw tx   -> tests/fixtures/tapscript_big.txt, gitignored; regenerate
 *                        with `python3 validation/fetch_tapscript_scale.py --big
 *                        tests/fixtures`. Absent => those cases SKIP loudly and
 *                        the test still exits 0, rather than failing merely
 *                        because the Core oracle is offline.
 */
